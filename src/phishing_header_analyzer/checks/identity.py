"""Sender identity checks: mismatched domains and display name tricks."""

from __future__ import annotations

import re

from ..config import Config
from ..findings import Finding
from ..parser import ParsedHeaders, domain_of
from ..util import compact, is_within, org_label, same_org
from .esp import expected_msgid, hiring_sender

CATEGORY = "identity"
_EMAIL_IN_TEXT = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")


def run(parsed: ParsedHeaders, config: Config) -> list[Finding]:
    out: list[Finding] = []
    frm = parsed.from_

    if frm is None or not frm.domain:
        out.append(Finding("FROM-MISSING", CATEGORY, "medium", 10, "No usable From address",
                           "The message has no parseable From address."))
        return out

    fd = frm.domain
    platform = hiring_sender(fd)

    # Reply-To pointing somewhere else: the core of most BEC payment scams.
    for rt in parsed.reply_to:
        if rt.domain and not same_org(rt.domain, fd):
            freemail = any(is_within(rt.domain, f) for f in config.freemail_domains)
            if platform and not freemail:
                # A hiring platform sends; replies go back to the employer. The reverse of
                # the scam pattern, where replies are steered away from the brand.
                out.append(Finding(
                    "REPLYTO-EMPLOYER", CATEGORY, "info", 0,
                    f"Replies go to {rt.domain}, not the hiring platform",
                    f"{platform} sent the message and replies go to the employer's own domain. "
                    "That's normal for hiring platforms.",
                    {"from_domain": fd, "reply_to": rt.address, "platform": platform},
                ))
                continue
            out.append(Finding(
                "REPLYTO-MISMATCH", CATEGORY, "high" if freemail else "medium", 25 if freemail else 15,
                "Reply-To goes to a different domain" + (" (free mail provider)" if freemail else ""),
                "Replies will go to a different organization than the apparent sender. "
                "This is how payment-redirect and gift-card scams collect responses.",
                {"from_domain": fd, "reply_to": rt.address},
            ))

    if parsed.return_path and parsed.return_path.domain and not same_org(parsed.return_path.domain, fd):
        out.append(Finding(
            "RETURN-PATH-MISMATCH", CATEGORY, "medium", 10, "Return-Path domain differs from From",
            "The envelope sender (where bounces go) belongs to a different domain than "
            "the visible From. Legitimate for some mailing services, common in spoofing.",
            {"from_domain": fd, "return_path": parsed.return_path.address},
        ))

    if parsed.sender and parsed.sender.domain and not same_org(parsed.sender.domain, fd):
        out.append(Finding(
            "SENDER-MISMATCH", CATEGORY, "low", 5, "Sender header domain differs from From",
            "The message claims to be sent on behalf of the From address by another domain.",
            {"from_domain": fd, "sender": parsed.sender.address},
        ))

    if parsed.message_id_domain and not same_org(parsed.message_id_domain, fd):
        generator = expected_msgid(parsed)
        if generator:
            out.append(Finding(
                "MSGID-PLATFORM", CATEGORY, "info", 0, f"Message-ID generated by {generator}",
                f"The Message-ID comes from {generator}'s servers, which is normal for mail sent "
                "through it.",
                {"from_domain": fd, "message_id_domain": parsed.message_id_domain},
            ))
        else:
            out.append(Finding(
                "MSGID-MISMATCH", CATEGORY, "low", 5, "Message-ID domain differs from From",
                "The Message-ID was generated by a different domain than the sender's. Often "
                "reveals the real sending host. Weak on its own because many services do this.",
                {"from_domain": fd, "message_id_domain": parsed.message_id_domain},
            ))

    # Display name tricks
    name = frm.display_name or ""
    for embedded in _EMAIL_IN_TEXT.findall(name):
        ed = domain_of(embedded)
        if embedded.lower() != frm.address and not same_org(ed, fd):
            out.append(Finding(
                "DISPLAY-NAME-ADDRESS", CATEGORY, "high", 20,
                "Display name shows a different email address",
                "Many mail clients show only the display name, so the reader sees an "
                "address that is not the real sender.",
                {"display_name": name, "actual_address": frm.address},
            ))
            break

    name_c = compact(name)
    if name_c:
        for watched in config.watched_domains:
            brand = compact(org_label(watched) or "")
            if len(brand) >= 4 and brand in name_c and not is_within(fd, watched) and not same_org(fd, watched):
                if platform:
                    detail = (f"The display name uses {watched}'s brand, but the message was sent "
                              f"from {fd}, the domain of {platform}, a hiring platform. It may be "
                              "sent on the brand's behalf, but nothing in the email proves the "
                              "brand is behind it. Verify through the brand's own careers site.")
                else:
                    detail = ("The display name claims to be a protected brand, but the message "
                              "was sent from a domain that brand does not own.")
                ev = {"display_name": name, "brand_domain": watched, "from_domain": fd}
                if platform:
                    ev["platform"] = platform
                out.append(Finding(
                    "DISPLAY-NAME-BRAND", CATEGORY, "high", 20,
                    "Display name uses a brand the sending domain doesn't belong to",
                    detail, ev,
                ))
                break

    return out
